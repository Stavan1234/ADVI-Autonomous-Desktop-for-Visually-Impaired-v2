from __future__ import annotations

import hashlib
from pathlib import Path

RELEASE_ID = "0.3.4-final-reliability"


def source_fingerprint(project_root: Path | None = None) -> str:
    """Fingerprint the complete production Python source surface.

    The runtime fingerprint must change when any shipped ADVI Python module changes.
    Keeping a short hand-maintained file list is too easy to forget when a new
    controller/capability module is introduced, so the fingerprint walks src/advi
    deterministically and excludes generated bytecode caches.
    """
    root = project_root or Path(__file__).resolve().parents[3]
    source_root = root / "src/advi"
    digest = hashlib.sha256()
    files = sorted(
        path for path in source_root.rglob("*.py")
        if "__pycache__" not in path.parts
    )
    for path in files:
        digest.update(str(path.relative_to(root)).replace("\\", "/").encode())
        try:
            digest.update(path.read_bytes())
        except OSError:
            digest.update(b"<missing>")
    return digest.hexdigest()[:16]
